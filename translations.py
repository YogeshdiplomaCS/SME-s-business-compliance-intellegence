    """Translate `key` into `lang`; optional {placeholders} are filled from kwargs."""
    value = TRANSLATIONS.get(lang, {}).get(key)
    if value is None:
        value = TRANSLATIONS["en"].get(key)
    if value is None:
        value = str(key)
    if kwargs:
        try:
            value = value.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return value


